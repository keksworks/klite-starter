package auth

import ch.tutteli.atrium.api.fluent.en_GB.toEqual
import ch.tutteli.atrium.api.verbs.expect
import com.sun.net.httpserver.Headers
import db.DBTest
import db.Id
import db.TestData.user
import io.mockk.every
import io.mockk.mockk
import klite.*
import org.junit.jupiter.api.Test
import users.User
import users.UserRepository
import java.sql.Connection
import java.sql.PreparedStatement
import javax.sql.DataSource

class UserSessionStoreTest: DBTest() {
  abstract class MockableExchange: OriginalHttpExchange()

  val requestHeaders = Headers()
  val responseHeaders = Headers()

  /** counts prepared statements, to prove that the session and the user really come from one roundtrip */
  val statements = mutableListOf<String>()
  val countingDb = object: DataSource by db {
    override fun getConnection(): Connection {
      val conn = db.connection
      return object: Connection by conn {
        override fun prepareStatement(sql: String, autoGeneratedKeys: Int): PreparedStatement =
          conn.prepareStatement(sql, autoGeneratedKeys).also { statements += sql }
      }
    }
  }

  val store = UserSessionStore(countingDb)
  val testUser = user.copy(id = Id(456), email = Email("session@example.com"))

  @Test fun `loads session and its user in one query`() {
    UserRepository(countingDb).save(testUser)
    val session = store.load(newExchange())
    session["userId"] = testUser.id
    store.save(newExchange(), session)

    statements.clear()
    val exchange = newExchange(cookie = savedCookieValue!!)
    val loaded = store.load(exchange)

    expect(loaded.isNew).toEqual(false)
    expect(loaded.get<Id<User>>("userId")).toEqual(testUser.id)
    expect(exchange.user).toEqual(testUser)
    expect(statements.size).toEqual(1)
  }

  @Test fun `loads session without a user`() {
    val session = store.load(newExchange())
    session["emailCode"] = "test@example.com:123456"
    store.save(newExchange(), session)

    val exchange = newExchange(cookie = savedCookieValue!!)
    val loaded = store.load(exchange)

    expect(loaded["emailCode"]).toEqual("test@example.com:123456")
    expect(exchange.userOrNull).toEqual(null)
  }

  private val savedCookieValue get() = responseHeaders["Set-Cookie"]?.single()?.substringAfter("S=")?.substringBefore(';')

  private fun newExchange(cookie: String? = null): HttpExchange {
    requestHeaders.clear()
    responseHeaders.clear()
    cookie?.let { requestHeaders.add("Cookie", "S=$it") }
    val original = mockk<MockableExchange>(relaxed = true) {
      every { requestMethod } returns "GET"
      every { responseCode } returns -1
      every { requestHeaders } returns this@UserSessionStoreTest.requestHeaders
      every { responseHeaders } returns this@UserSessionStoreTest.responseHeaders
    }
    return HttpExchange(original, mockk<RouterConfig>(relaxed = true), store, "req-id")
  }
}
